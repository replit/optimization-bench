def load_adapter():
    sys.path.insert(0, str(TASK / "environment/workload"))
    try:
        spec = importlib.util.spec_from_file_location(
            "sqlite_ranked_adapter", TASK / "environment/workload/task.py")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return module
    finally:
        sys.path.pop(0)


class AuthorTests(unittest.TestCase):
    def test_exact_sections_and_line_origins(self):
        text = "First?\n======\n\nA café.\n\nSecond?\n=======\n\nFull\nbody.\n"
        self.assertEqual(list(author.sections("docs/a.rst", text)), [
            ("docs/a.rst:1", "First?", "A café."),
            ("docs/a.rst:6", "Second?", "Full\nbody."),
        ])

    def packet(self, root, files):
        archive = root / "source.tar.gz"
        with tarfile.open(archive, "w:gz") as stream:
            for name, body in files:
                data = body.encode()
                info = tarfile.TarInfo("project/" + name)
                info.size = len(data)
                stream.addfile(info, io.BytesIO(data))
        spec = {
            "archive_prefix": "project", "notices": ["LICENSE"],
            "document_root": "docs/", "question_root": "docs/faq/",
            "suffixes": [".rst"], "exclude_exact_paths": ["docs/excluded.rst"],
            "exclude_path_prefixes": ["docs/build/"],
        }
        return archive, spec

    def test_deduplication_query_semantics_and_exclusions(self):
        with tempfile.TemporaryDirectory() as tmp:
            archive, spec = self.packet(Path(tmp), [
                ("LICENSE", "Verbatim test-only license text"),
                ("docs/faq/z.rst", "How how WHY?\n============\n\nExact body.\n"),
                ("docs/faq/a.rst", "How how WHY?\n============\n\nExact body.\n"),
                ("docs/excluded.rst", "Bad?\n====\n\nExcluded.\n"),
                ("docs/build/one.rst", "Bad?\n====\n\nExcluded build.\n"),
                ("docs/generated.rst", ".. This file is automatically generated\n\nBad?\n====\n\nGenerated.\n"),
                ("docs/guide.rst", "A guide\n=======\n\nUnmodified body.\n"),
            ])
            docs, requests, inventory, notices, fingerprints = author.corpus(archive, spec)
            self.assertEqual(docs, [
                (1, "docs/faq/a.rst:1", "How how WHY?", "Exact body."),
                (2, "docs/guide.rst:1", "A guide", "Unmodified body."),
            ])
            self.assertEqual(requests, [
                ("docs/faq/a.rst:1", "How how WHY?", '"how" OR "why"'),
            ])
            self.assertEqual(len(fingerprints), 2)
            self.assertEqual(len(inventory), 3)
            self.assertEqual(notices["LICENSE"], b"Verbatim test-only license text")

    def test_rejects_missing_notice_and_unsafe_member(self):
        with tempfile.TemporaryDirectory() as tmp:
            archive, spec = self.packet(Path(tmp), [
                ("docs/faq/a.rst", "Why?\n====\n\nBody.\n"),
            ])
            with self.assertRaisesRegex(ValueError, "license notice"):
                author.corpus(archive, spec)
            archive, spec = self.packet(Path(tmp), [
                ("LICENSE", "License"), ("../docs/faq/a.rst", "Why?\n====\n\nBody.\n"),
            ])
            with self.assertRaisesRegex(ValueError, "Unsafe"):
                author.corpus(archive, spec)

    def test_refuses_reauthoring_an_existing_packet(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "preserved").write_bytes(b"untouched")
            with self.assertRaisesRegex(ValueError, "overwrite"):
                author.build(root / "unused", {}, root, root / "unused", root / "unused")
            self.assertEqual((root / "preserved").read_bytes(), b"untouched")

    def test_combines_projects_once_and_excludes_public_duplicates(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            sources = []
            for name, title, body in (
                ("first", "First?", "Original first body."),
                ("second", "Second?", "Original second body."),
            ):
                archive, spec = self.packet(root, [
                    ("LICENSE", "Verbatim license"),
                    ("docs/faq/a.rst", "Shared?\n=======\n\nShared body.\n"),
                    ("docs/faq/b.rst", f"{title}\n{'=' * len(title)}\n\n{body}\n"),
                    ("docs/notice.rst", "Notice\n======\n\nCopyright retained exactly.\n"),
                ])
                raw = archive.read_bytes()
                archive.rename(root / (name + ".tar.gz"))
                sources.append({**spec, "id": name, "repository": f"https://github.com/org/{name}",
                                "archive_bytes": len(raw), "archive_sha256": author.digest(raw)})
            excluded = {author.digest(b"First?\0Original first body.")}
            docs, requests, inventory, notices, fingerprints, removed = author.combined_corpus(
                root, {"sources": sources}, excluded)
            self.assertEqual([row[2] for row in docs], ["Shared?", "Notice", "Second?"])
            self.assertEqual([row[0] for row in docs], [1, 2, 3])
            self.assertEqual(len(requests), 3)
            self.assertEqual(len(inventory), 6)
            self.assertEqual(removed, 1)
            self.assertFalse(fingerprints & excluded)
            self.assertEqual(notices["first/docs/notice.rst"],
                             b"Notice\n======\n\nCopyright retained exactly.\n")
            self.assertTrue(all(row[1].startswith(("first/", "second/")) for row in docs))

    def test_project_identity_normalization_and_duplicate_project_rejection(self):
        sources = [
            {"repository": "https://github.com/Org/Project.git/"},
            {"repository": "https://github.com/org/project"},
        ]
        self.assertEqual(len(author.project_set({"sources": sources})), 1)
        with self.assertRaisesRegex(ValueError, "only once"):
            author.combined_corpus(Path("unused"), {"sources": sources})

    def test_document_only_project_is_allowed_but_an_empty_query_batch_is_not(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            archive, spec = self.packet(root, [
                ("LICENSE", "Verbatim license"),
                ("docs/guide.rst", "An authentic guide\n==================\n\nComplete text.\n"),
            ])
            with self.assertRaisesRegex(ValueError, "No eligible"):
                author.corpus(archive, spec)
            docs, requests, *_ = author.corpus(archive, spec, require_requests=False)
            self.assertEqual(len(docs), 1)
            self.assertEqual(requests, [])
            raw = archive.read_bytes()
            archive.rename(root / "guide.tar.gz")
            source = {**spec, "id": "guide", "repository": "https://github.com/org/guide",
                      "archive_bytes": len(raw), "archive_sha256": author.digest(raw)}
            with self.assertRaisesRegex(ValueError, "No eligible combined"):
                author.combined_corpus(root, {"sources": [source]})


class AdapterTests(unittest.TestCase):
    def setUp(self):
        self.adapter = load_adapter()
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        (self.root / "inputs/files").mkdir(parents=True)
        (self.root / "scratch").mkdir()
        database, requests = b"public test fixture database", b"q\tWhy?\t\"why\"\n"
        sha = lambda value: hashlib.sha256(value).hexdigest()
        self.row = {
            "path": "test-search", "family": "ranked-documents", "bytes": len(database),
            "sha256": sha(database), "requests_bytes": len(requests),
            "requests_sha256": sha(requests), "requests": 1,
        }
        for value in (database, requests):
            (self.root / "inputs/files" / sha(value)).write_bytes(value)
        self.ctx = SimpleNamespace(inputs=self.root / "inputs", scratch=self.root / "scratch",
                                   build=self.root / "same-candidate")
        self.case = SimpleNamespace(id="test-search", data=self.row)
        self.success = SimpleNamespace(exit_code=0, stdout=b"", stderr=b"",
                                       leftovers=[],
                                       telemetry={"execution_protocol": "complete"})

    def test_both_families_use_the_same_candidate_and_resident_protocol(self):
        search = self.adapter.prepare(self.case, self.ctx)[0]
        self.assertEqual(search.argv[0], str(self.ctx.build / "search"))
        self.assertEqual(search.argv[-1], "resident")
        self.assertTrue(search.resident)
        self.row["family"] = "country-filtered-facets"
        facets = self.adapter.prepare(self.case, self.ctx)[0]
        self.assertEqual(facets.argv[0], str(self.ctx.build / "facets"))
        self.assertEqual(facets.argv[-1], "1")
        self.assertTrue(facets.resident)

    def test_tampered_input_and_unknown_family_fail_before_execution(self):
        (self.ctx.inputs / "files" / self.row["sha256"]).write_bytes(b"wrong")
        with self.assertRaisesRegex(ValueError, "Database commitment"):
            self.adapter.prepare(self.case, self.ctx)
        self.row["family"] = "unregistered"
        with self.assertRaisesRegex(ValueError, "Unknown workload"):
            self.adapter.prepare(self.case, self.ctx)

    def test_complete_output_required_and_database_must_remain_unchanged(self):
        self.adapter.prepare(self.case, self.ctx)
        with self.assertRaisesRegex(ValueError, "Complete regular"):
            self.adapter.collect(self.case, self.ctx, [self.success])
        (self.ctx.scratch / "result.bin").write_bytes(b"complete typed output")
        self.assertEqual(self.adapter.collect(self.case, self.ctx, [self.success]),
                         {"test-search": b"complete typed output"})
        (self.ctx.scratch / "input.db-wal").write_bytes(b"unexpected")
        with self.assertRaisesRegex(ValueError, "Read-only"):
            self.adapter.collect(self.case, self.ctx, [self.success])

    def test_missing_native_operation_is_rejected(self):
        self.adapter.prepare(self.case, self.ctx)
        with self.assertRaisesRegex(ValueError, "Native workload"):
            self.adapter.collect(self.case, self.ctx, [])

    def test_missing_stop_or_leftover_process_is_rejected_even_with_complete_output(self):
        self.adapter.prepare(self.case, self.ctx)
        (self.ctx.scratch / "result.bin").write_bytes(b"otherwise complete output")
        for protocol, leftovers in (
            ("missing-ready-stop", []), ("missing-result-stop", []),
            ("timeout", []), ("complete", [{"pid": 123}]),
        ):
            with self.subTest(protocol=protocol, leftovers=bool(leftovers)):
                result = SimpleNamespace(exit_code=0, stdout=b"", stderr=b"",
                                         telemetry={"execution_protocol": protocol},
                                         leftovers=leftovers)
                with self.assertRaisesRegex(ValueError, "lifecycle incomplete"):
                    self.adapter.collect(self.case, self.ctx, [result])


if __name__ == "__main__":
    unittest.main()
